#!/usr/bin/env python3
"""Summarize a raw Lua call trace (a game log written with tools/lua-trace).

Usage: summarize.py TRACE.log [--bindings work/lua-bindings.json] [-o SUMMARY.md]

For each traced Lua state: the order in which distinct functions were first
called, and how often each was called. Names are matched to the engine binding
list so method names use its class names (moho table keys such as
`unit_methods` are mapped by majority vote over their methods).
"""
import argparse
import collections
import json
import sys

DETAIL = 20
SIDE_LISTS = {"user": {"0xf58680", "0xf58670"}, "sim": {"0xf59114", "0xf58670"}}


class State:
    def __init__(self, name):
        self.name = name
        self.kind = name.split("-", 1)[0]
        self.wrapped = 0
        self.calls = {}
        self.detail = collections.Counter()
        self.snapshot = {}
        self.snapshot_seq = 0

    def counts(self):
        names = set(self.detail) | set(self.snapshot)
        return {n: max(self.detail[n], self.snapshot.get(n, 0)) for n in names}


def parse(path):
    states = {}
    with open(path, encoding="latin-1") as log:
        for line in log:
            at = line.find("TRACE|")
            if at < 0:
                continue
            fields = line[at + 6:].rstrip("\r\n").split("|")
            kind, state = fields[0], states.setdefault(fields[1], State(fields[1]))
            if kind == "START":
                state.wrapped = int(fields[2])
            elif kind == "CALL":
                seq, name = int(fields[2]), fields[3]
                state.detail[name] += 1
                if name not in state.calls:
                    state.calls[name] = (seq, fields[4], fields[5] if len(fields) > 5 else "")
            elif kind == "COUNTS":
                seq = int(fields[2])
                if seq != state.snapshot_seq:
                    state.snapshot_seq, state.snapshot = seq, {}
                for entry in fields[3].split():
                    name, _, count = entry.rpartition("=")
                    state.snapshot[name] = int(count)
    return states


def class_map(states, bindings):
    """Map moho table keys to binding classes, per state kind, by method-name vote."""
    by_side = collections.defaultdict(lambda: collections.defaultdict(set))
    for b in bindings:
        for kind, heads in SIDE_LISTS.items():
            if b["list_head"] in heads and b["class"] != "<global>":
                by_side[kind][b["name"]].add(b["class"])
    mapping = {}
    for kind in SIDE_LISTS:
        votes = collections.defaultdict(collections.Counter)
        for state in states.values():
            if state.kind != kind:
                continue
            for name in state.counts():
                if ":" in name:
                    key, method = name.split(":", 1)
                    for cls in by_side[kind].get(method, ()):
                        votes[key][cls] += 1
        for key, counter in votes.items():
            mapping[(kind, key)] = counter.most_common(1)[0][0]
    return mapping


def resolve(kind, name, mapping, known):
    if ":" in name:
        key, method = name.split(":", 1)
        cls = mapping.get((kind, key), key)
        label = f"{cls}:{method}"
        return label, (cls, method) in known[kind]
    return name, ("<global>", name) in known[kind]


def summarize(path, bindings):
    states = parse(path)
    known = {kind: {(b["class"], b["name"]) for b in bindings if b["list_head"] in heads}
             for kind, heads in SIDE_LISTS.items()}
    mapping = class_map(states, bindings)
    out = [f"# Lua call trace summary: `{path}`", ""]
    out.append("Generated by `tools/lua-trace/summarize.py`. A state is one Lua state "
               "(`user` = front end or session UI, `sim` = simulation). Calls before the "
               "`/lua/globalInit.lua` hook ran are not traced. Counts are the larger of the "
               f"last count snapshot and the detailed lines (only the first {DETAIL} calls of "
               "each function are detailed), so a count can lag the end of the run.")
    out.append("")
    out.append("| State | Wrapped | Calls (last seq) | Distinct called | Of them listed bindings |")
    out.append("| --- | --- | --- | --- | --- |")
    for state in states.values():
        counts = state.counts()
        listed = sum(1 for n in counts if resolve(state.kind, n, mapping, known)[1])
        last = max([state.snapshot_seq] + [s for s, _, _ in state.calls.values()])
        out.append(f"| `{state.name}` | {state.wrapped} | {last} | {len(counts)} | {listed} |")
    for kind in SIDE_LISTS:
        seen = set()
        for state in states.values():
            if state.kind == kind:
                seen |= {resolve(kind, n, mapping, known)[0]
                         for n in state.counts() if resolve(kind, n, mapping, known)[1]}
        if seen:
            out.append("")
            out.append(f"Distinct {kind}-side listed bindings called (all {kind} states): "
                       f"{len(seen)} of {len(known[kind])}.")
    for state in states.values():
        counts = state.counts()
        out += ["", f"## `{state.name}`", "", "First-call order:", ""]
        out.append("| # | Seq | Function | Listed | First caller | First arguments |")
        out.append("| --- | --- | --- | --- | --- | --- |")
        first = sorted(state.calls.items(), key=lambda item: item[1][0])
        for i, (name, (seq, caller, args)) in enumerate(first, 1):
            label, listed = resolve(state.kind, name, mapping, known)
            args = args if len(args) <= 60 else args[:60] + "..."
            args = args.replace("`", "'")
            out.append(f"| {i} | {seq} | `{label}` | {'yes' if listed else 'no'} | "
                       f"`{caller}` | `{args}` |")
        out += ["", "Call counts:", ""]
        out.append("| Function | Calls |")
        out.append("| --- | --- |")
        for name, count in sorted(counts.items(), key=lambda item: (-item[1], item[0])):
            out.append(f"| `{resolve(state.kind, name, mapping, known)[0]}` | {count} |")
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("trace")
    parser.add_argument("--bindings", default="work/lua-bindings.json")
    parser.add_argument("-o", "--output")
    args = parser.parse_args()
    with open(args.bindings) as f:
        bindings = json.load(f)["bindings"]
    text = summarize(args.trace, bindings)
    if args.output:
        with open(args.output, "w") as f:
            f.write(text)
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
